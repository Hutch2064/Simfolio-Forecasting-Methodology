"""Local single52 campaign control; importing this module never starts work.

``init`` creates a campaign; ``add``/``remove`` atomically change desired state;
``run`` reconciles that state. Each model runs in its own process group from a
content-addressed copy of source. Removal finishes the current task and retains
all checkpoints. There is deliberately no model wall-clock timeout.
"""
from __future__ import annotations

import argparse
import fcntl
import gzip
import hashlib
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import time
import uuid
from contextlib import contextmanager
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THREAD_KEYS = ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS",
               "VECLIB_MAXIMUM_THREADS", "NUMEXPR_NUM_THREADS", "NUMBA_NUM_THREADS",
               "BLIS_NUM_THREADS", "GOTO_NUM_THREADS")
PROTOCOL = "catalogue52-terminal-log-empirical-crps-240-v1"
EXPECTED = {"portfolios": 52, "tasks": 2652, "cells": 455832}


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                     allow_nan=False).encode()).hexdigest()


def file_hash(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def atomic(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            json.dump(value, stream, indent=2, sort_keys=True, allow_nan=False)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


@contextmanager
def lock(path, *, nonblocking=False):
    with Path(path).open("a") as stream:
        fcntl.flock(stream, fcntl.LOCK_EX | (fcntl.LOCK_NB if nonblocking else 0))
        try:
            yield
        finally:
            fcntl.flock(stream, fcntl.LOCK_UN)


def read(path):
    return json.loads(Path(path).read_text())


def source_files(root):
    """Conservative closure: all src resources and tools source/configuration.

    Generated bytecode/compiler caches are never inputs. Source-tree symlinks
    are rejected to prevent imports escaping the frozen closure.
    """
    result = []
    for folder in (root / "src", root / "tools"):
        for path in sorted(folder.rglob("*")):
            relative = path.relative_to(root)
            if any(part in {"__pycache__", ".pytest_cache", ".git"} for part in relative.parts):
                continue
            if path.is_symlink():
                raise ValueError(f"source symlinks are not supported: {relative}")
            if path.is_file() and path.suffix not in {".pyc", ".nbc", ".nbi"}:
                result.append(path)
    result.extend(path for path in (root / "pyproject.toml", root / "requirements-lock.txt")
                  if path.is_file())
    return result


def freeze_source(root, snapshots):
    root, snapshots = Path(root).resolve(), Path(snapshots)
    hashes = {str(p.relative_to(root)): file_hash(p) for p in source_files(root)}
    if "tools/catalogue52/worker.py" not in hashes:
        raise ValueError("worker missing from source closure")
    binding = digest(hashes)
    destination = snapshots / binding
    if not destination.exists():
        snapshots.mkdir(parents=True, exist_ok=True)
        temporary = Path(tempfile.mkdtemp(prefix="snapshot-", dir=snapshots))
        try:
            for relative, expected in hashes.items():
                target = temporary / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(root / relative, target)
                if file_hash(target) != expected:
                    raise ValueError("source changed during snapshot construction")
                target.chmod(0o444)
            atomic(temporary / "snapshot.json", {"sha256": binding, "files": hashes})
            (temporary / "snapshot.json").chmod(0o444)
            temporary.rename(destination)
            for folder in sorted(destination.rglob("*"), reverse=True):
                if folder.is_dir():
                    folder.chmod(0o555)
            destination.chmod(0o555)
        finally:
            if temporary.exists():
                shutil.rmtree(temporary)
    verify_snapshot(destination, binding)
    return destination, binding


def verify_snapshot(snapshot, expected):
    snapshot = Path(snapshot)
    receipt = read(snapshot / "snapshot.json")
    if receipt["sha256"] != expected or digest(receipt["files"]) != expected:
        raise ValueError("snapshot identity mismatch")
    actual = {str(p.relative_to(snapshot)): file_hash(p) for p in source_files(snapshot)}
    if actual != receipt["files"]:
        raise ValueError("immutable source snapshot changed")


def storage_ok(campaign, config, *, additional_bytes=0):
    used = 0
    for path in Path(campaign).rglob("*"):
        try:
            if path.is_file():
                used += path.stat().st_size
        except FileNotFoundError:
            pass  # An atomic writer replaced its temporary during the audit.
    return (used + additional_bytes + 2 * 1024 ** 2 <= config["budget_gib"] * 1024 ** 3
            and shutil.disk_usage(campaign).free - additional_bytes >= config["min_free_gib"] * 1024 ** 3)


def initialize(campaign, data, environment_manifest, *, budget_gib=60, min_free_gib=100):
    if budget_gib <= 0 or min_free_gib < 0:
        raise ValueError("invalid storage bounds")
    campaign = Path(campaign).resolve()
    campaign.mkdir(parents=True, exist_ok=True)
    with lock(campaign / "control.lock"):
        if (campaign / "campaign.json").exists():
            raise ValueError("campaign already exists")
        manifest_path = Path(environment_manifest)
        opener = gzip.open if manifest_path.suffix == ".gz" else open
        with opener(manifest_path, "rt") as stream:
            reference = json.load(stream)
        if not isinstance(reference.get("python"), str) or not reference.get("packages"):
            raise ValueError("saved environment requires python and packages")
        config = {"protocol": PROTOCOL, "expected": EXPECTED, "simulations": 240,
                  "data": str(Path(data).resolve()),
                  "data_manifest_sha256": file_hash(Path(data) / "canonical_data_manifest.json"),
                  "environment": {"python": reference["python"], "packages": reference["packages"]},
                  "saved_environment_sha256": file_hash(manifest_path),
                  "budget_gib": float(budget_gib), "min_free_gib": float(min_free_gib)}
        atomic(campaign / "campaign.json", config)
        atomic(campaign / "control.json", {"models": {}})


def add_model(campaign, model_id, *, name=None, adapter=None, environment=None,
              indices=None, source_root=ROOT):
    campaign = Path(campaign).resolve()
    name = name or model_id
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", name) or name in {".", ".."}:
        raise ValueError("model name must be a safe directory name")
    environment = environment or {}
    if any(not key.startswith("SIMFOLIO_") or not isinstance(value, str)
           for key, value in environment.items()):
        raise ValueError("model environment must contain explicit SIMFOLIO_ string values")
    if "SIMFOLIO_RESEARCH_FIT_CACHE" in environment:
        raise ValueError("persistent fit caches are not enabled in this campaign")
    if indices is not None and (not indices or len(set(indices)) != len(indices)
                                or any(i < 0 or i >= EXPECTED["tasks"] for i in indices)):
        raise ValueError("invalid smoke indices")
    with lock(campaign / "control.lock"):
        config = read(campaign / "campaign.json")
        if not storage_ok(campaign, config):
            raise ValueError("campaign storage budget/free-space gate failed")
        output = campaign / "models" / name
        archived = output / "archive-receipt.json"
        if archived.exists() and read(archived).get("status") == "archived":
            raise ValueError("archived model requires explicit restoration before add/resume")
        registration = output / "registration.json"
        existing = read(registration) if registration.exists() else None
        if existing:
            # Resume keeps its original closure even after another model was
            # added to the live checkout. A changed version needs a new name.
            snapshot, source_digest = Path(existing["snapshot"]), existing["source_sha256"]
            verify_snapshot(snapshot, source_digest)
        else:
            if any((campaign / "snapshots").is_relative_to(Path(source_root).resolve() / folder)
                   for folder in ("src", "tools")):
                raise ValueError("campaign storage must be outside the source closure")
            source_bytes = sum(p.stat().st_size for p in source_files(Path(source_root)))
            if not storage_ok(campaign, config, additional_bytes=source_bytes):
                raise ValueError("snapshot would exceed campaign storage budget/free-space gate")
            snapshot, source_digest = freeze_source(source_root, campaign / "snapshots")
        if adapter is not None:
            source = Path(adapter)
            if source.is_absolute() or ".." in source.parts or not (snapshot / source).is_file():
                raise ValueError("adapter must be a file within the frozen source snapshot")
        spec = {"name": name, "model_id": model_id, "adapter": adapter,
                "snapshot": str(snapshot), "source_sha256": source_digest,
                "environment": environment, "indices": indices,
                "campaign_sha256": digest(config)}
        output.mkdir(parents=True, exist_ok=True)
        if registration.exists() and read(registration) != spec:
            raise ValueError("existing model binding differs; use a new name for changed source/specification")
        atomic(registration, spec)
        control = read(campaign / "control.json")
        control["models"][name] = {"desired": "running", "request": uuid.uuid4().hex}
        atomic(campaign / "control.json", control)
    return spec


def remove_model(campaign, name, *, force=False, reason=None):
    if force and not (reason and reason.strip()):
        raise ValueError("force removal requires an explicit reason")
    campaign = Path(campaign)
    with lock(campaign / "control.lock"):
        control = read(campaign / "control.json")
        if name not in control["models"]:
            raise ValueError("unknown model")
        control["models"][name]["desired"] = "removed"
        control["models"][name]["force"] = bool(force)
        control["models"][name]["reason"] = reason
        atomic(campaign / "control.json", control)


def process_identity(pid):
    result = subprocess.run(["ps", "-ww", "-p", str(pid), "-o", "lstart=", "-o", "pgid=",
                             "-o", "stat=", "-o", "command="], check=False, capture_output=True, text=True)
    fields = result.stdout.strip().split(None, 7)
    if result.returncode or len(fields) != 8 or fields[6].startswith("Z"):
        return None
    return {"started": " ".join(fields[:5]), "pgid": int(fields[5]), "command": fields[7]}


def verified_process(state):
    if (not isinstance(state.get("pid"), int) or state["pid"] <= 0
            or not re.fullmatch(r"[a-f0-9]{32}", state.get("token", ""))):
        return False
    current = process_identity(state["pid"])
    return bool(current and current["started"] == state["started"]
                and current["pgid"] == state["pid"]
                and re.search(r"(?:^|\s)--token\s+" + re.escape(state["token"]) + r"(?:\s|$)",
                              current["command"])
                and state["worker"] in current["command"])


def request_stop(state):
    if not verified_process(state):
        return False
    ready = Path(state["ready"])
    if not ready.exists() or read(ready).get("token") != state["token"]:
        return False  # Do not signal before the worker has installed handlers.
    try:
        # Only the leader handles cooperative stopping. Signaling the whole
        # group could interrupt an adapter's legitimate in-flight child fit.
        os.kill(state["pid"], signal.SIGUSR1)
    except ProcessLookupError:
        return False
    return True


def force_stop(state, output, reason, *, now=None):
    """Explicit user removal only: verified group TERM, then KILL after 15s.

    A lost/reused leader identity never authorizes a group signal.
    """
    if not verified_process(state):
        return False
    now = time.time() if now is None else now
    if "force_started" not in state:
        progress_path = Path(output) / "progress.json"
        progress = read(progress_path) if progress_path.exists() else {}
        atomic(Path(output) / "interruption.json", {"reason": reason, "forced": True,
               "time": now, "pid": state["pid"], "token": state["token"],
               "interrupted_task": progress.get("current_task"),
               "completed_tasks": progress.get("completed_tasks", 0),
               "full_score_eligible": False})
        try:
            os.killpg(state["pid"], signal.SIGTERM)
        except ProcessLookupError:
            return False
        state["force_started"] = now
        state["stopping"] = True
    elif now - state["force_started"] >= 15 and not state.get("force_killed"):
        try:
            os.killpg(state["pid"], signal.SIGKILL)
        except ProcessLookupError:
            return False
        state["force_killed"] = True
    return True


class Controller:
    def __init__(self, campaign, *, max_models=1, python=sys.executable, nice=10):
        if max_models < 1 or not 0 <= nice <= 19:
            raise ValueError("invalid resource bounds")
        self.root, self.max_models = Path(campaign).resolve(), max_models
        self.python, self.nice = str(Path(python).absolute()), nice
        self.config = read(self.root / "campaign.json")
        self.children = {}
        self.next_storage_check = 0
        self.storage_available = False

    def launch(self, name, request):
        output = self.root / "models" / name
        spec = read(output / "registration.json")
        snapshot = Path(spec["snapshot"])
        verify_snapshot(snapshot, spec["source_sha256"])
        token = uuid.uuid4().hex
        worker = str(snapshot / "tools/catalogue52/worker.py")
        env = {k: v for k, v in os.environ.items() if not k.startswith("SIMFOLIO_")}
        env.update(spec["environment"])
        env.update({key: "1" for key in THREAD_KEYS})
        cache = output / "runtime"
        cache.mkdir(exist_ok=True)
        env.update({"PYTHONPATH": str(snapshot / "src"), "PYTHONNOUSERSITE": "1",
                    "PYTHONDONTWRITEBYTECODE": "1", "NUMBA_CACHE_DIR": str(cache / "numba"),
                    "TMPDIR": str(cache), "MPLCONFIGDIR": str(cache / "matplotlib"),
                    "PYTHONHASHSEED": "0", "OMP_DYNAMIC": "FALSE", "MKL_DYNAMIC": "FALSE"})
        with (output / "worker.log").open("ab", buffering=0) as log:
            process = subprocess.Popen([self.python, "-s", worker, "--registration",
                                        str(output / "registration.json"), "--token", token,
                                        "--nice", str(self.nice)], cwd=snapshot, env=env,
                                       stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        self.children[name] = process
        identity = process_identity(process.pid)
        for _ in range(20):
            if identity is not None or process.poll() is not None:
                break
            time.sleep(0.01)
            identity = process_identity(process.pid)
        state = {"pid": process.pid, "token": token, "worker": worker,
                 "started": None if identity is None else identity["started"],
                 "ready": str(output / "ready.json"),
                 "request": request, "stopping": False}
        atomic(output / "process.json", state)
        return state

    def tick(self, *, shutdown=False):
        if time.monotonic() >= self.next_storage_check:
            self.storage_available = storage_ok(self.root, self.config)
            atomic(self.root / "storage.json", {"available": self.storage_available, "time": time.time()})
            self.next_storage_check = time.monotonic() + 60
        control = read(self.root / "control.json")
        active = {}
        for name, desired in control["models"].items():
            output = self.root / "models" / name
            process_file = output / "process.json"
            state = read(process_file) if process_file.exists() else None
            child = self.children.get(name)
            if child is not None:
                child.poll()  # Reap exited children before checking PID reuse.
            live = state is not None and verified_process(state)
            if live:
                active[name] = state
                if state.get("force_started") or (desired["desired"] == "removed" and desired.get("force")):
                    force_stop(state, output, desired.get("reason"))
                    atomic(process_file, state)
                elif (shutdown or desired["desired"] == "removed") and not state["stopping"]:
                    state["stopping"] = request_stop(state)
                    atomic(process_file, state)
                continue
            if shutdown or desired["desired"] != "running":
                continue
            status_file = output / "progress.json"
            status = read(status_file) if status_file.exists() else {}
            if status.get("status") == "complete":
                continue
            if state and state["request"] == desired["request"]:
                continue  # Failed/crashed workers require an explicit add/resume.
            active[name] = None  # Queue without consuming a process slot yet.
        count = sum(state is not None for state in active.values())
        if not shutdown and self.storage_available:
            for name, state in active.items():
                if state is None and count < self.max_models:
                    active[name] = self.launch(name, control["models"][name]["request"])
                    count += 1
        atomic(self.root / "controller.json", {"live_models": count, "max_models": self.max_models,
               "shutting_down": shutdown, "time": time.time()})
        return count


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaign", required=True, type=Path)
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("init")
    init.add_argument("--data", required=True, type=Path)
    init.add_argument("--environment-manifest", required=True, type=Path)
    init.add_argument("--budget-gib", type=float, default=60)
    init.add_argument("--min-free-gib", type=float, default=100)
    add = sub.add_parser("add")
    add.add_argument("model_id")
    add.add_argument("--name")
    add.add_argument("--adapter")
    add.add_argument("--environment-json", type=json.loads, default={})
    add.add_argument("--env", action="append", default=[], metavar="SIMFOLIO_KEY=VALUE")
    add.add_argument("--indices", help="Smoke only; comma-separated indices, never a full score")
    remove = sub.add_parser("remove")
    remove.add_argument("name")
    remove.add_argument("--force", action="store_true", help="Explicit TERM/15s/KILL removal of only this verified model group")
    remove.add_argument("--reason")
    run = sub.add_parser("run")
    run.add_argument("--max-models", type=int, default=1)
    run.add_argument("--python", default=sys.executable)
    run.add_argument("--nice", type=int, default=10)
    sub.add_parser("status")
    args = parser.parse_args(argv)
    if args.command == "init":
        initialize(args.campaign, args.data, args.environment_manifest,
                   budget_gib=args.budget_gib, min_free_gib=args.min_free_gib)
    elif args.command == "add":
        environment = dict(args.environment_json)
        for setting in args.env:
            key, separator, value = setting.partition("=")
            if not separator or (key in environment and environment[key] != value):
                raise ValueError("invalid or conflicting --env value")
            environment[key] = value
        add_model(args.campaign, args.model_id, name=args.name, adapter=args.adapter,
                  environment=environment,
                  indices=None if args.indices is None else [int(i) for i in args.indices.split(",")])
    elif args.command == "remove":
        remove_model(args.campaign, args.name, force=args.force, reason=args.reason)
    elif args.command == "status":
        control = read(args.campaign / "control.json")
        for name, state in control["models"].items():
            progress = args.campaign / "models" / name / "progress.json"
            state["progress"] = read(progress) if progress.exists() else None
            startup = args.campaign / "models" / name / "startup.json"
            state["startup"] = read(startup) if startup.exists() else None
            process = args.campaign / "models" / name / "process.json"
            state["live"] = process.exists() and verified_process(read(process))
        print(json.dumps(control, indent=2, sort_keys=True))
    else:
        controller = Controller(args.campaign, max_models=args.max_models,
                                python=args.python, nice=args.nice)
        stopping = False
        def stop(signum, frame):
            nonlocal stopping
            stopping = True
        signal.signal(signal.SIGTERM, stop)
        signal.signal(signal.SIGINT, stop)
        with lock(args.campaign / "controller.lock", nonblocking=True):
            while True:
                live = controller.tick(shutdown=stopping)
                if stopping and not live:
                    break
                time.sleep(1)


if __name__ == "__main__":
    main()
